"""自绘 OpenPose 骨架（COCO 18 点）

为什么不用自动检测：长裙/遮挡/侧身时检测器经常认不出腿，出来是站姿。
自己画坐标反而完全可控。

输出：skel_kneel.png / skel_sit.png / skel_lying.png
"""
import os
from PIL import Image, ImageDraw

OUT = os.environ.get("LANXI_POSE_OUT", "./poses")
os.makedirs(OUT, exist_ok=True)

# COCO 18 点：0鼻 1颈 2右肩 3右肘 4右腕 5左肩 6左肘 7左腕
#            8右髋 9右膝 10右踝 11左髋 12左膝 13左踝 14右眼 15左眼 16右耳 17左耳
COLORS = {
    (1, 2): (255, 0, 0), (2, 3): (255, 85, 0), (3, 4): (255, 170, 0),
    (1, 5): (255, 255, 0), (5, 6): (170, 255, 0), (6, 7): (85, 255, 0),
    (1, 8): (0, 255, 85), (8, 9): (0, 255, 170), (9, 10): (0, 255, 255),
    (1, 11): (0, 170, 255), (11, 12): (0, 85, 255), (12, 13): (0, 0, 255),
    (1, 0): (85, 0, 255), (0, 14): (170, 0, 255), (0, 15): (255, 0, 255),
    (14, 16): (255, 0, 170), (15, 17): (255, 0, 85),
}

KNEEL = {
    0: (372, 250), 1: (368, 320),
    2: (424, 330), 3: (450, 430), 4: (430, 500),
    5: (312, 330), 6: (286, 430), 7: (306, 500),
    8: (404, 540), 9: (470, 660), 10: (500, 790),
    11: (336, 545), 12: (300, 700), 13: (360, 800),
    14: (360, 242), 15: (386, 242), 16: (342, 254), 17: (404, 254),
}

SIT = {
    0: (352, 250), 1: (352, 322),
    2: (410, 332), 3: (446, 420), 4: (470, 470),
    5: (294, 332), 6: (258, 420), 7: (234, 470),
    8: (392, 540), 9: (530, 560), 10: (540, 780),
    11: (312, 540), 12: (450, 590), 13: (455, 800),
    14: (340, 242), 15: (366, 242), 16: (322, 254), 17: (384, 254),
}

LYING = {
    0: (210, 300), 1: (280, 320),
    2: (300, 380), 3: (380, 420), 4: (450, 470),
    5: (300, 260), 6: (380, 220), 7: (450, 180),
    8: (470, 340), 9: (620, 300), 10: (760, 270),
    11: (470, 400), 12: (620, 450), 13: (770, 500),
    14: (198, 288), 15: (222, 312), 16: (182, 292), 17: (238, 316),
}


def draw(name, pts, w, h, line=10, dot=7):
    img = Image.new("RGB", (w, h), (0, 0, 0))
    d = ImageDraw.Draw(img)
    for (a, b), col in COLORS.items():
        if a in pts and b in pts:
            d.line([pts[a], pts[b]], fill=col, width=line)
    for x, y in pts.values():
        d.ellipse([x - dot, y - dot, x + dot, y + dot], fill=(255, 255, 255))
    p = os.path.join(OUT, f"skel_{name}.png")
    img.save(p)
    print("骨架", p)


if __name__ == "__main__":
    draw("kneel", KNEEL, 768, 1120)
    draw("sit", SIT, 768, 1120)
    draw("lying", LYING, 1120, 768)
